 /*Faça um algoritmo que exiba todos números de 100 a 1
*/

#include <stdio.h>
#include <stdlib.h>

int main(){
    for (int i = 100; i >= 1; i--){
        printf("%d \n", i);
    }//for
return 0;
}//main